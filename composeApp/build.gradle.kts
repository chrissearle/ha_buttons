// ./gradlew installLocal
//   -> ~/Applications/Buttons.app       (self-contained app bundle incl. trimmed JVM)
//   -> ~/.local/bin/buttons             (launcher script; passes args, e.g. --config <path>)
// Override with -Pbuttons.appDir=... / -Pbuttons.binDir=...
val home: String = System.getProperty("user.home")
val appDir = providers.gradleProperty("buttons.appDir").orElse("$home/Applications")
val binDir = providers.gradleProperty("buttons.binDir").orElse("$home/.local/bin")

tasks.register("installLocal") {
    group = "distribution"
    description = "Installs Buttons.app into ~/Applications and a `buttons` launcher into ~/.local/bin (macOS)"
    dependsOn("createDistributable")

    val appSource = layout.buildDirectory.dir("compose/binaries/main/app/Buttons.app")
    val appTarget = appDir.map { File(it, "Buttons.app") }
    val launcher = binDir.map { File(it, "buttons") }
    val isMac = System.getProperty("os.name").startsWith("Mac")

    doLast {
        check(isMac) { "installLocal currently only supports macOS" }
        val source = appSource.get().asFile
        val target = appTarget.get()
        val script = launcher.get()

        // Replace only our own bundle; ditto preserves permissions, symlinks and the code signature.
        target.deleteRecursively()
        target.parentFile.mkdirs()
        val ditto = ProcessBuilder("ditto", source.absolutePath, target.absolutePath).inheritIO().start()
        check(ditto.waitFor() == 0) { "ditto failed copying $source to $target" }

        script.parentFile.mkdirs()
        script.writeText(
            """
            |#!/bin/sh
            |# Generated by ./gradlew installLocal
            |exec "${target.absolutePath}/Contents/MacOS/Buttons" "${'$'}@"
            |""".trimMargin(),
        )
        script.setExecutable(true)

        println("Installed $target")
        println("Launcher  $script")
    }
}
